/**
 * Infers accurate substantive Labor Law articles based on semantic keywords and category.
 * NEVER defaults to "المادة 14" (which is the number of the statute, not the article).
 */
export function inferArticlesFromTopic(
  text: string,
  category?: string
): string[] {
  const norm = (text || '')
    .replace(/[إأآا]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .toLowerCase();

  // 1. Check topic keywords
  if (
    norm.includes('نساء') ||
    norm.includes('امومه') ||
    norm.includes('حضانه') ||
    norm.includes('وضع') ||
    norm.includes('رضاعه') ||
    norm.includes('حوامل')
  ) {
    return ['المادة 50', 'المادة 51', 'المادة 52', 'المادة 53', 'المادة 54'];
  }

  if (
    norm.includes('احداث') ||
    norm.includes('اطفال') ||
    norm.includes('حدث') ||
    norm.includes('طفل') ||
    norm.includes('بطاقه تفتيش')
  ) {
    return ['المادة 58', 'المادة 59', 'المادة 60', 'المادة 64'];
  }

  if (norm.includes('تدرج مهني') || norm.includes('متدرج') || norm.includes('تلمذه')) {
    return ['المادة 65', 'المادة 66'];
  }

  if (
    norm.includes('اجانب') ||
    norm.includes('اجنبي') ||
    norm.includes('غير مصريين') ||
    norm.includes('استقدام') ||
    norm.includes('ترخيص عمل الاجنبي')
  ) {
    return ['المادة 67', 'المادة 68', 'المادة 69', 'المادة 70', 'المادة 71'];
  }

  if (
    norm.includes('الحاق العماله') ||
    norm.includes('وكالات التشغيل') ||
    norm.includes('شركات التوظيف') ||
    norm.includes('خطاب ضمان')
  ) {
    return ['المادة 39', 'المادة 40', 'المادة 41'];
  }

  if (
    norm.includes('صندوق التدريب') ||
    norm.includes('تمويل التدريب') ||
    norm.includes('نسبه اشتراك')
  ) {
    return ['المادة 19', 'المادة 20'];
  }

  if (
    norm.includes('مراكز التدريب') ||
    norm.includes('ترخيص مراكز') ||
    norm.includes('اعتماد البرامج')
  ) {
    return ['المادة 22', 'المادة 23'];
  }

  if (
    norm.includes('جزاءات') ||
    norm.includes('تاديب') ||
    norm.includes('لائحه تنظيم العمل') ||
    norm.includes('تحقيق') ||
    norm.includes('مساءله')
  ) {
    return ['المادة 110', 'المادة 111'];
  }

  if (
    norm.includes('اعياد') ||
    norm.includes('اجازات رسميه') ||
    norm.includes('مناسبات رسميه') ||
    norm.includes('عطلات')
  ) {
    return ['المادة 99'];
  }

  if (
    norm.includes('ساعات العمل') ||
    norm.includes('فترات الراحه') ||
    norm.includes('مناوبه') ||
    norm.includes('ورديات')
  ) {
    return ['المادة 80', 'المادة 81', 'المادة 82', 'المادة 85'];
  }

  if (
    norm.includes('الحد الادني للاجور') ||
    norm.includes('حمايه الاجور') ||
    norm.includes('wps') ||
    norm.includes('مرتبات') ||
    norm.includes('اجور')
  ) {
    return ['المادة 82', 'المادة 88', 'المادة 90'];
  }

  if (
    norm.includes('اجهزه السلامه') ||
    norm.includes('لجان السلامه') ||
    norm.includes('اخصائي سلامه')
  ) {
    return ['المادة 227', 'المادة 228'];
  }

  if (
    norm.includes('تفتيش السلامه') ||
    norm.includes('خطر داهم') ||
    norm.includes('وقف اداري') ||
    norm.includes('قياسات بيئيه')
  ) {
    return ['المادة 232', 'المادة 233'];
  }

  if (
    norm.includes('فحص طبي') ||
    norm.includes('امراض مهنيه') ||
    norm.includes('مهمات الوقايه') ||
    norm.includes('سلامه وصحه مهنيه') ||
    norm.includes('بيئه العمل')
  ) {
    return ['المادة 208', 'المادة 216'];
  }

  if (
    norm.includes('ضبطيه قضائيه') ||
    norm.includes('تفتيش ذكي') ||
    norm.includes('تصالح') ||
    norm.includes('تفتيش العمل') ||
    norm.includes('مفتش')
  ) {
    return ['المادة 245', 'المادة 246', 'المادة 260'];
  }

  if (
    norm.includes('وساطه') ||
    norm.includes('تحكيم') ||
    norm.includes('نزاع جماعي') ||
    norm.includes('منازعات عمل') ||
    norm.includes('اضراب')
  ) {
    return ['المادة 168', 'المادة 170', 'المادة 180'];
  }

  if (
    norm.includes('توثيق') ||
    norm.includes('عقد العمل') ||
    norm.includes('فتره اختبار') ||
    norm.includes('عقود العمل')
  ) {
    return ['المادة 72', 'المادة 73', 'المادة 74'];
  }

  // 2. Check category defaults
  if (category) {
    if (category.includes('السلامة')) return ['المادة 208', 'المادة 216'];
    if (category.includes('الفئات الأولى')) return ['المادة 50', 'المادة 58'];
    if (category.includes('التدريب')) return ['المادة 19', 'المادة 22'];
    if (category.includes('الأجور')) return ['المادة 88', 'المادة 90'];
    if (category.includes('تفتيش')) return ['المادة 245', 'المادة 246'];
    if (category.includes('منازعات')) return ['المادة 168', 'المادة 170'];
    if (category.includes('عقود العمل')) return ['المادة 72', 'المادة 74'];
  }

  return ['المادة 1', 'المادة 72'];
}

/**
 * Sanitizes a decision to ensure it is accurately linked to its true Labor Law articles,
 * completely purging any erroneous fallback to "المادة 14" (which stemmed from confusing Law 14/2025 with Article 14).
 */
export function sanitizeDecisionLawArticles<T extends {
  id?: string;
  decisionNumber?: string;
  title?: string;
  category?: string;
  relatedLawArticles?: string[];
  legalBasisSummary?: string;
  enactedLawArticlesDetail?: { articleNumber: string; topic: string; mandate: string }[];
  preamble?: string;
  executingSubject?: string;
}>(decision: T): T {
  const decNum = String(decision.decisionNumber || '').trim();
  const canonical = CANONICAL_DECISION_MAPPINGS[decNum];

  // If known canonical decision, always enforce authentic articles
  if (canonical) {
    return {
      ...decision,
      relatedLawArticles: canonical.articles,
      legalBasisSummary: canonical.summary,
      enactedLawArticlesDetail: canonical.details,
    };
  }

  // Check if current articles are exclusively or erroneously "المادة 14"
  const currentArticles = decision.relatedLawArticles || [];
  const hasOnlyArt14 =
    currentArticles.length === 0 ||
    (currentArticles.length === 1 && currentArticles[0].trim() === 'المادة 14') ||
    (currentArticles.includes('المادة 14') && !decision.title?.includes('مكاتب التشغيل'));

  if (hasOnlyArt14) {
    const textCorpus = `${decision.title || ''} ${decision.executingSubject || ''} ${decision.preamble || ''}`;
    const inferred = inferArticlesFromTopic(textCorpus, decision.category);

    return {
      ...decision,
      relatedLawArticles: inferred,
      legalBasisSummary: generateLegalBasisSummary(inferred),
    };
  }

  // Filter out stray "المادة 14" if present alongside real articles
  if (currentArticles.includes('المادة 14') && currentArticles.length > 1) {
    const cleaned = currentArticles.filter((a) => a.trim() !== 'المادة 14');
    return {
      ...decision,
      relatedLawArticles: cleaned,
      legalBasisSummary: generateLegalBasisSummary(cleaned),
    };
  }

  return decision;
}

