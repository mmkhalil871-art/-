/**
 * Normalizes an article text string (e.g. "50", "مادة 50", "المادة (50)") to standardized "المادة 50"
 */
export function normalizeArticleName(raw: string): string {
  const trimmed = raw.trim();
  if (!trimmed) return '';

  // Extract digits
  const match = trimmed.match(/\d+/);
  if (match) {
    return `المادة ${match[0]}`;
  }

  // Handle words like الأولى، الثانية
  if (trimmed.includes('الأولى')) return 'المادة الأولى';
  if (trimmed.includes('الثانية')) return 'المادة الثانية';

  return trimmed.startsWith('المادة') ? trimmed : `المادة ${trimmed}`;
}

/**
 * Parses user input string (comma or newline separated) into an array of normalized article strings
 */
export function parseArticlesString(input: string): string[] {
  if (!input) return [];

  const parts = input.split(/[،,;\n]+/);
  const result: string[] = [];
  const seen = new Set<string>();

  for (const part of parts) {
    const normalized = normalizeArticleName(part);
    if (normalized && !seen.has(normalized)) {
      seen.add(normalized);
      result.push(normalized);
    }
  }

  return result;
}

/**
 * Generates an accurate legal basis summary text based on article numbers
 */
export function generateLegalBasisSummary(articles: string[]): string {
  if (!articles || articles.length === 0) {
    return 'صادر تنفيذاً لأحكام قانون العمل رقم 14 لسنة 2025';
  }

  const numbers = articles
    .map((a) => a.replace(/[^\d]/g, ''))
    .filter(Boolean);

  if (numbers.length > 0) {
    return `صادر تنفيذاً للمواد (${numbers.join('، ')}) من قانون العمل رقم 14 لسنة 2025`;
  }

  return `صادر تنفيذاً للمواد (${articles.join('، ')}) من قانون العمل رقم 14 لسنة 2025`;
}
